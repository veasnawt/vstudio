export type Language = "en" | "km";

/** The one translation function everything else calls — a plain function (not a hook) so it works
 *  both inside React components (via `useTranslation` below, which supplies `language` reactively)
 *  and inside imperative, non-component code like `editorStore.ts`'s own actions (which already have
 *  `get().language` on hand and call this directly, with no hook available to them). */
export function translateText(language: Language, text: string, params?: Record<string, string | number>): string {
  const translated = language === "km" ? (KM_TRANSLATIONS[text] ?? text) : text;
  if (!params) return translated;
  return Object.entries(params).reduce((s, [key, value]) => s.replaceAll(`{${key}}`, String(value)), translated);
}
